"""The filler cue's model as data (B29, rec-27): what filler_loop.pack writes from convert.py's header, read by the
recorder's own parser (firmware/recorder/octo_kws_blob.h, compiled on the Mac), and sent by device.send_filler_model."""

import hashlib
import random
import shutil
import struct
import subprocess
from pathlib import Path

import pytest

from octo import device as D
from octo import filler_loop as FLP

ROOT = Path(__file__).resolve().parent.parent

# A blob's bytes as hex on a line; prints "ok NAME|THRESHOLD|MODEL_LEN|TOTAL|SHA" or "no".
HARNESS = r"""
#include <stdio.h>
#include "octo_kws_blob.h"
static char line[400000];
static uint8_t b[200000];
int main(void) {
  while (fgets(line, sizeof line, stdin)) {
    size_t n = 0;
    for (char *p = line; p[0] && p[1] && p[0] != '\n'; p += 2) { unsigned v; sscanf(p, "%2x", &v); b[n++] = (uint8_t)v; }
    oc_kws_head h;
    size_t total = n >= OC_KWS_HEAD ? oc_kws_parse(b, 0x40000, &h) : 0;
    if (!total) { printf("no\n"); continue; }
    printf("ok %s|%.3f|%u|%u|", h.name, h.threshold, (unsigned)h.model_len, (unsigned)total);
    for (int i = 0; i < 32; i++) printf("%02x", h.sha[i]);
    printf("\n");
  }
  return 0;
}
"""


def header(model: bytes, fb: list[float], thr: float = 0.95) -> str:
    """An octo_filler_model.h as convert.py writes one."""
    lines = ["// Generated by convert.py from the owner's voice: never commit (see .gitignore).\n#pragma once\n",
             f"const float KWS_THRESHOLD = {thr}f;\n", f"alignas(16) const unsigned char kws_model[{len(model)}] = {{\n"]
    lines += ["  " + ",".join(str(b) for b in model[k:k + 20]) + ",\n" for k in range(0, len(model), 20)]
    lines.append("};\n")
    lines.append("const float kws_fb[257][40] = {\n")
    lines += ["  {" + ",".join(f"{v:.8e}f" for v in fb[r * 40:(r + 1) * 40]) + "},\n" for r in range(257)]
    lines.append("};\n")
    return "".join(lines)


def _fake(n=23001, seed=1):
    rnd = random.Random(seed)
    fb = [rnd.uniform(0, 0.02) if rnd.random() < 0.1 else 0.0 for _ in range(257 * 40)]
    return bytes(rnd.randrange(256) for _ in range(n)), list(struct.unpack("<10280f", struct.pack("<10280f", *fb)))  # float32


@pytest.fixture(scope="module")
def parse(tmp_path_factory):
    if not shutil.which("cc"):
        pytest.skip("no C compiler")
    tmp = tmp_path_factory.mktemp("kws")
    (tmp / "k.c").write_text(HARNESS)
    subprocess.run(["cc", "-O1", "-Wall", "-Werror", "-Wno-unused-function", "-I", str(ROOT / "firmware" / "recorder"),
                    str(tmp / "k.c"), "-o", str(tmp / "k")], check=True)

    def go(blobs: list[bytes]) -> list[str]:
        return subprocess.run([str(tmp / "k")], input="".join(b.hex() + "\n" for b in blobs), capture_output=True,
                              text=True, check=True).stdout.splitlines()
    return go


def test_the_recorder_reads_what_the_lab_packs(parse):
    model, fb = _fake()
    blob = FLP.pack(header(model, fb), "uh")
    assert len(blob) == 80 + 23004 + 257 * 40 * 4 and blob[80:80 + len(model)] == model   # 16-byte aligned, padded to 4
    assert list(struct.unpack("<10280f", blob[80 + 23004:])) == fb  # exactly the floats convert.py wrote
    name, thr, mlen, total, sha = parse([blob])[0].removeprefix("ok ").split("|")
    assert (name, thr, int(mlen), int(total)) == ("uh", "0.950", len(model), len(blob))
    assert sha == hashlib.sha256(blob[80:]).hexdigest()


def test_the_recorder_refuses_what_isnt_a_model(parse):
    blob = FLP.pack(header(*_fake(800)), "you know")
    bad = [b"OKWX" + blob[4:], blob[:4] + b"\x02" + blob[5:],                      # magic, version
           blob[:8] + b"a\"b" + blob[11:], blob[:8] + b"x" * 24 + blob[32:],       # a quote; no end to the name
           blob[:32] + struct.pack("<f", 1.0) + blob[36:],                         # a threshold the cue can't use
           blob[:40] + struct.pack("<I", 4) + blob[44:],                           # not 257 x 40 floats
           blob[:36] + struct.pack("<I", 0x40000) + blob[40:]]                     # bigger than a slot
    assert parse([blob] + bad) == [parse([blob])[0]] + ["no"] * len(bad)
    for name in ("", "x" * 24, 'say "so"', "ćao"):
        with pytest.raises(ValueError):
            FLP.pack(header(*_fake(800)), name)


class Recorder:
    """The firmware's /filler/model/* as recorder.ino does them, enough for the Mac's side."""

    def __init__(self, takes=True, starts=True):
        self.takes, self.starts, self.got = takes, starts, b""
        self.status = {"fw": "rec-27", "filler_models": takes, "boot": 1, "filler_name": "you know", "filler_sha": "old"}
        self.ip = "10.0.0.9"
        self.restarts_after = None  # status answers left on the old boot before it restarts

    def call(self, path, body=None, raw=False):
        if path == "/status":
            if self.restarts_after is not None:
                if self.restarts_after == 0:
                    self.status, self.restarts_after = {**self.next, "boot": self.status["boot"] + 1}, None
                else:
                    self.restarts_after -= 1
            return self.status
        if path == "/filler/model/begin":
            self.size, self.sha, self.got = body["size"], body["sha256"], b""
            return {"ready": True}
        if path == "/filler/model/data":
            import base64
            assert body["offset"] == len(self.got)
            self.got += base64.b64decode(body["data"])
            return {"done": len(self.got)}
        if path == "/filler/model/finish":
            assert len(self.got) == self.size and hashlib.sha256(self.got).hexdigest() == self.sha
            sha = hashlib.sha256(self.got[80:]).hexdigest()[:16]
            self.next = ({**self.status, "filler_name": self.got[8:32].rstrip(b"\0").decode(), "filler_sha": sha}
                         if self.starts else {**self.status, "filler_reverted": "uh"})
            self.restarts_after = 2  # it still answers on the old boot for a moment, as the chip does
            return {"restarting": True}
        if path == "/filler/model/undo":
            self.next, self.restarts_after = {**self.status, "filler_name": "you know", "filler_sha": "old"}, 1
            return {"restarting": True}
        raise AssertionError(path)


def test_the_mac_sends_it_in_pieces_and_checks_it_started():
    blob = FLP.pack(header(*_fake()), "uh")
    rec = Recorder()
    st = D.send_filler_model(rec, blob, log=lambda m: None, wait=lambda s: None)
    assert rec.got == blob and st["filler_name"] == "uh"
    with pytest.raises(D.DeviceError, match="went back"):
        D.send_filler_model(Recorder(starts=False), blob, log=lambda m: None, wait=lambda s: None)
    with pytest.raises(D.DeviceError, match="rec-27"):
        D.send_filler_model(Recorder(takes=False), blob, log=lambda m: None, wait=lambda s: None)
    st = D.undo_filler_model(rec, log=lambda m: None, wait=lambda s: None)
    assert st["boot"] == 3 and st["filler_sha"] == "old"   # waited for the boot after Undo's restart
